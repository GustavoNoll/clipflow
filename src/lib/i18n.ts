type MessageKey = keyof typeof messages.en;

export function translate(language: Language, key: MessageKey, vars?: Record<string, string | number>) {
  let value = String(messages[language]?.[key] ?? messages.en[key] ?? key);
  if (!vars) return value;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.split(`{${name}}`).join(String(replacement));
  }
  return value;
}

export function useI18n() {
  const { settings } = useSettings();
  return useMemo(() => {
    const language = settings.language ?? "en";
    return {
      language,
      t: (key: MessageKey, vars?: Record<string, string | number>) =>
        translate(language, key, vars),
    };
  }, [settings.language]);
}

export function translateCategoryName(language: Language, name: string) {
  const normalized = name.trim().toLowerCase();
  const key =
    normalized === "history"
      ? "categoryHistory"
      : normalized === "prompts"
        ? "categoryPrompts"
        : normalized === "assets"
          ? "categoryAssets"
          : normalized === "screenshots"
            ? "categoryScreenshots"
            : normalized === "colors"
              ? "categoryColors"
              : null;

  return key ? translate(language, key) : name;
}

export function translateItemType(language: Language, type: string) {
  const key =
    type === "text"
      ? "typeText"
      : type === "url"
        ? "typeUrl"
        : type === "code"
          ? "typeCode"
          : type === "image"
            ? "typeImage"
            : type === "file"
              ? "typeFile"
              : type === "color"
                ? "typeColor"
                : null;

  return key ? translate(language, key) : type;
}

export function formatRelativeTimeForLanguage(iso: string, language: Language) {
  const date = new Date(iso);
  const diffMs = Date.now() - date.getTime();
  const diffMin = Math.floor(diffMs / 60000);
  const locale = language === "pt" ? "pt-BR" : language === "es" ? "es" : "en";

  if (diffMin < 1) {
    return new Intl.RelativeTimeFormat(locale, { numeric: "auto" }).format(0, "minute");
  }
  if (diffMin < 60) {
    return new Intl.RelativeTimeFormat(locale, { numeric: "auto" }).format(-diffMin, "minute");
  }
  const diffH = Math.floor(diffMin / 60);
  if (diffH < 24) {
    return new Intl.RelativeTimeFormat(locale, { numeric: "auto" }).format(-diffH, "hour");
  }
  const diffD = Math.floor(diffH / 24);
  if (diffD < 7) {
    return new Intl.RelativeTimeFormat(locale, { numeric: "auto" }).format(-diffD, "day");
  }
  return date.toLocaleDateString(locale);
}
